"""Evidence-only architecture graph without Gemini (dev / missing API key)."""

from __future__ import annotations

from app.architecture.evidence import (
    build_internal_import_links,
    build_package_summaries,
    dominant_application_kind,
    package_key,
    production_route_entries,
)
from app.schemas.analysis import RepositoryAnalysisPayload
from app.schemas.architecture import ArchitectureEdge, ArchitectureGraph, ArchitectureNode, NodeKind


def re_slug(value: str) -> str:
    import re

    return re.sub(r"[^a-zA-Z0-9_-]+", "_", value.strip())[:48] or "item"


def build_deterministic_architecture(analysis: RepositoryAnalysisPayload) -> ArchitectureGraph:
    """Build a richer evidence-only graph from detections, packages, and imports."""

    nodes: list[ArchitectureNode] = []
    edges: list[ArchitectureEdge] = []
    warnings = [
        "Evidence-only deterministic architecture (not generated by Gemini).",
    ]
    node_ids: set[str] = set()

    def add_node(node: ArchitectureNode) -> None:
        if node.id in node_ids:
            return
        node_ids.add(node.id)
        nodes.append(node)

    def add_edge(
        *,
        edge_id: str,
        source: str,
        target: str,
        edge_type: str,
        evidence: list[str],
        label: str | None = None,
    ) -> None:
        if source not in node_ids or target not in node_ids or source == target:
            return
        edges.append(
            ArchitectureEdge(
                id=edge_id,
                source=source,
                target=target,
                type=edge_type,  # type: ignore[arg-type]
                label=label or edge_type.replace("_", " "),
                evidence=evidence[:5],
            )
        )

    app_kind: NodeKind = dominant_application_kind(analysis)  # type: ignore[assignment]
    app_id = "application"
    lang_evidence = [f"{lang.language} ({lang.file_count} files)" for lang in analysis.summary.languages[:6]]
    add_node(
        ArchitectureNode(
            id=app_id,
            label=analysis.repository.full_name or analysis.repository.name,
            kind=app_kind,
            description="Application root inferred from repository languages and structure.",
            file_paths=analysis.summary.important_files[:6],
            evidence=[analysis.repository.url or analysis.repository.name, *lang_evidence[:3]],
        )
    )

    # Layer nodes from detections
    if analysis.detections.frontend_components:
        paths = analysis.detections.frontend_components[:10]
        add_node(
            ArchitectureNode(
                id="frontend_layer",
                label="Frontend / UI",
                kind="frontend",
                file_paths=paths,
                evidence=paths[:5],
                description=f"{len(analysis.detections.frontend_components)} frontend component file(s).",
            )
        )
        add_edge(
            edge_id="app_uses_frontend",
            source=app_id,
            target="frontend_layer",
            edge_type="uses",
            evidence=paths[:3],
            label="uses",
        )

    if analysis.detections.backend_services:
        paths = analysis.detections.backend_services[:10]
        add_node(
            ArchitectureNode(
                id="service_layer",
                label="Services / business logic",
                kind="service",
                file_paths=paths,
                evidence=paths[:5],
                description=f"{len(analysis.detections.backend_services)} service file(s).",
            )
        )
        add_edge(
            edge_id="app_calls_services",
            source=app_id,
            target="service_layer",
            edge_type="calls",
            evidence=paths[:3],
            label="calls",
        )

    if analysis.detections.data_access_modules:
        paths = analysis.detections.data_access_modules[:10]
        add_node(
            ArchitectureNode(
                id="data_layer",
                label="Data access",
                kind="database",
                file_paths=paths,
                evidence=paths[:5],
                description=f"{len(analysis.detections.data_access_modules)} data-access module(s).",
            )
        )
        src = "service_layer" if "service_layer" in node_ids else app_id
        add_edge(
            edge_id=f"{src}_uses_data",
            source=src,
            target="data_layer",
            edge_type="uses",
            evidence=paths[:3],
            label="uses",
        )

    if analysis.detections.configuration_files:
        paths = analysis.detections.configuration_files[:10]
        add_node(
            ArchitectureNode(
                id="config_layer",
                label="Configuration",
                kind="config",
                file_paths=paths,
                evidence=paths[:5],
            )
        )
        add_edge(
            edge_id="app_depends_config",
            source=app_id,
            target="config_layer",
            edge_type="depends_on",
            evidence=paths[:3],
            label="depends on",
        )

    production_routes = production_route_entries(analysis, limit=40)
    if production_routes:
        route_paths = sorted({r["file_path"] for r in production_routes if r.get("file_path")})[:12]
        route_evidence = [
            f"{r['method']} {r.get('path') or ''} ({r['file_path']})".strip() for r in production_routes[:10]
        ]
        add_node(
            ArchitectureNode(
                id="api_layer",
                label="API / controllers",
                kind="api",
                description=f"{len(production_routes)} production route(s).",
                file_paths=route_paths,
                evidence=route_evidence,
            )
        )
        add_edge(
            edge_id="app_exposes_api",
            source=app_id,
            target="api_layer",
            edge_type="exposes",
            evidence=route_evidence[:3],
            label="exposes",
        )
        if "service_layer" in node_ids:
            add_edge(
                edge_id="api_calls_services",
                source="api_layer",
                target="service_layer",
                edge_type="calls",
                evidence=route_paths[:3],
                label="calls",
            )
        if "data_layer" in node_ids and "service_layer" not in node_ids:
            add_edge(
                edge_id="api_uses_data",
                source="api_layer",
                target="data_layer",
                edge_type="uses",
                evidence=analysis.detections.data_access_modules[:3],
                label="uses",
            )
    else:
        warnings.append(
            "No production API routes detected; API layer omitted "
            "(test/example routes stay classified in raw analysis only)."
        )

    if analysis.detections.tests:
        paths = analysis.detections.tests[:10]
        add_node(
            ArchitectureNode(
                id="test_layer",
                label="Tests",
                kind="test",
                file_paths=paths,
                evidence=paths[:5],
                description=f"{len(analysis.detections.tests)} test file(s).",
            )
        )
        add_edge(
            edge_id="tests_use_app",
            source="test_layer",
            target=app_id,
            edge_type="uses",
            evidence=paths[:3],
            label="tests",
        )

    for integration in analysis.detections.integrations[:8]:
        nid = f"ext_{re_slug(integration)}"
        add_node(
            ArchitectureNode(
                id=nid,
                label=integration,
                kind="external",
                evidence=[integration],
                file_paths=[],
                description="Detected integration from dependency/import evidence.",
            )
        )
        src = "data_layer" if "data_layer" in node_ids else app_id
        add_edge(
            edge_id=f"{src}_depends_{nid}",
            source=src,
            target=nid,
            edge_type="depends_on",
            evidence=[integration],
            label="depends on",
        )

    # Important packages as modules with import relationships
    packages = build_package_summaries(analysis, limit=12)
    # Skip generic docs-only packages for clarity
    skip_names = {"docs", "doc", "documentation", "examples", "example", "samples", "benchmarks"}
    package_node_ids: dict[str, str] = {}

    # Prefer packages that look architectural when detection layers are sparse
    detection_layer_count = sum(
        1
        for nid in ("frontend_layer", "service_layer", "data_layer", "api_layer")
        if nid in node_ids
    )
    package_limit = 8 if detection_layer_count <= 1 else 5

    for pkg in packages[:package_limit]:
        name = pkg["name"]
        if name.lower() in skip_names:
            continue
        kind = pkg["suggested_kind"]
        # Avoid duplicating a whole-layer node with same role when we already have that layer
        # Still include key packages as modules for structure.
        if kind in {"frontend", "service", "database", "api", "config", "test", "backend"}:
            node_kind: NodeKind = "module" if kind == "backend" else kind  # type: ignore[assignment]
        else:
            node_kind = "module"

        # If we already have a dedicated layer of that kind, keep package as module
        if kind == "frontend" and "frontend_layer" in node_ids:
            node_kind = "module"
        if kind == "service" and "service_layer" in node_ids:
            node_kind = "module"
        if kind == "database" and "data_layer" in node_ids:
            node_kind = "module"
        if kind == "api" and "api_layer" in node_ids:
            node_kind = "module"
        if kind == "config" and "config_layer" in node_ids:
            node_kind = "module"
        if kind == "test" and "test_layer" in node_ids:
            node_kind = "module"

        nid = f"pkg_{re_slug(name)}"
        sample_files = pkg["sample_files"][:6]
        evidence = sample_files[:]
        if pkg.get("sample_symbols"):
            evidence.extend(f"symbol:{s}" for s in pkg["sample_symbols"][:4])
        add_node(
            ArchitectureNode(
                id=nid,
                label=name,
                kind=node_kind,
                description=f"Package with {pkg['file_count']} analyzed file(s).",
                file_paths=sample_files,
                evidence=evidence[:8],
            )
        )
        package_node_ids[name] = nid
        # Attach package to the most relevant parent layer
        parent = app_id
        if node_kind == "frontend" and "frontend_layer" in node_ids:
            parent = "frontend_layer"
        elif node_kind == "service" and "service_layer" in node_ids:
            parent = "service_layer"
        elif node_kind == "database" and "data_layer" in node_ids:
            parent = "data_layer"
        elif node_kind == "api" and "api_layer" in node_ids:
            parent = "api_layer"
        elif node_kind == "test" and "test_layer" in node_ids:
            parent = "test_layer"
        elif node_kind == "config" and "config_layer" in node_ids:
            parent = "config_layer"
        add_edge(
            edge_id=f"{parent}_uses_{nid}",
            source=parent,
            target=nid,
            edge_type="uses",
            evidence=sample_files[:2] or [name],
            label="uses",
        )

    # Wire API packages from production routes
    if "api_layer" in node_ids:
        route_pkgs = {
            r.get("package")
            for r in production_routes
            if r.get("package") and r.get("package") in package_node_ids
        }
        for pkg_name in sorted(x for x in route_pkgs if x):
            add_edge(
                edge_id=f"api_imports_{package_node_ids[pkg_name]}",
                source="api_layer",
                target=package_node_ids[pkg_name],
                edge_type="imports",
                evidence=[f"routes in package {pkg_name}"],
                label="imports",
            )

    import_links = build_internal_import_links(analysis, limit=20)
    for link in import_links:
        src = package_node_ids.get(link["from_package"])
        tgt = package_node_ids.get(link["to_package"])
        if not src or not tgt:
            continue
        add_edge(
            edge_id=f"{src}_imports_{tgt}",
            source=src,
            target=tgt,
            edge_type="imports",
            evidence=link.get("evidence") or [f"{link['from_package']} → {link['to_package']}"],
            label="imports",
        )

    # Attach route files' packages to API when package nodes missing but path evidence exists
    if production_routes and "api_layer" in node_ids:
        for r in production_routes[:8]:
            pkg = r.get("package") or package_key(r.get("file_path") or "")
            if not pkg or pkg not in package_node_ids:
                continue
            add_edge(
                edge_id=f"api_exposes_via_{package_node_ids[pkg]}",
                source="api_layer",
                target=package_node_ids[pkg],
                edge_type="exposes",
                evidence=[f"{r['method']} {r.get('path') or ''} ({r['file_path']})".strip()],
                label="exposes",
            )

    if len(nodes) <= 1:
        warnings.append("Limited structural evidence; architecture graph is minimal.")

    langs = ", ".join(lang.language for lang in analysis.summary.languages[:5]) or "unknown"
    summary = (
        f"Evidence-only architecture for {analysis.repository.name} "
        f"({langs}; {len(nodes)} components, {len(edges)} relationships)."
    )

    return ArchitectureGraph(nodes=nodes, edges=edges, summary=summary, warnings=warnings)
